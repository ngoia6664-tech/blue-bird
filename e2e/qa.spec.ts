test('QA second tab refreshes chapter content when editing lock transfers', async ({ page, context }) => {
  await login(page); await work(page, 'tab-lock')
  await write(page, 'Bản gốc.')
  const second = await context.newPage()
  await second.goto(page.url())
  await expect(second.locator('.prose')).toHaveText('Bản gốc.')
  await expect(second.locator('.prose')).toHaveAttribute('contenteditable', 'false')
  await write(page, 'Bản mới đã lưu từ tab một.')
  await page.close()
  await expect(second.locator('.prose')).toHaveAttribute('contenteditable', 'true')
  await second.screenshot({ path: test.info().outputPath('lock-transfer.png'), fullPage: true })
  const transferred = await second.locator('.prose').innerText()
  await second.locator('.prose').press('Control+End')
  await second.locator('.prose').pressSequentially(' Viết tiếp ở tab hai.')
  await expect(second.locator('.save-state')).toHaveText('Đã đồng bộ', { timeout: 15000 })
  await second.reload()
  await test.info().attach('tab-transfer-content', { body: JSON.stringify({ transferred, persisted: await second.locator('.prose').innerText() }), contentType: 'application/json' })
  await expect(second.locator('.prose')).toContainText('Bản mới đã lưu từ tab một.')
})

test('QA remote quick note is not overwritten by leaving a previously saved info panel', async ({ page, browser }) => {
  await login(page); await work(page, 'notes')
  await page.getByLabel('Ghi chú nhanh').fill('Ghi chú ban đầu từ máy một')
  await page.getByLabel('Tiêu đề chương').click()
  const ctx = await browser.newContext()
  const remote = await ctx.newPage()
  await login(remote); await remote.goto(page.url())
  await expect(remote.getByLabel('Ghi chú nhanh')).toHaveValue('Ghi chú ban đầu từ máy một')
  await remote.getByLabel('Ghi chú nhanh').fill('Ghi chú từ máy thứ hai')
  await remote.getByLabel('Tiêu đề chương').click()
  await remote.reload()
  await expect(remote.getByLabel('Ghi chú nhanh')).toHaveValue('Ghi chú từ máy thứ hai')
  await page.getByRole('button', { name: 'Lịch sử phiên bản', exact: true }).click()
  await remote.reload()
  await expect(remote.getByLabel('Ghi chú nhanh')).toHaveValue('Ghi chú từ máy thứ hai')
  await ctx.close()
})

test('QA cover upload replacement removal and invalid file validation', async ({ page }) => {
  await login(page)
  const name = `QA cover ${Date.now()}`
  const coverOne = await page.screenshot()
  await page.getByRole('link', { name: 'Tạo tác phẩm', exact: true }).first().click()
  await page.getByLabel('Tên tác phẩm *').fill(name)
  await page.locator('input[type=file]').setInputFiles({ name: 'invalid.txt', mimeType: 'text/plain', buffer: Buffer.from('QA invalid image') })
  await expect(page.getByRole('alert')).toContainText('không phải ảnh')
  await page.locator('input[type=file]').setInputFiles({ name: 'qa-cover.png', mimeType: 'image/png', buffer: coverOne })
  await expect(page.locator('.cover img')).toBeVisible()
  const first = await page.locator('.cover img').getAttribute('src')
  await page.getByRole('button', { name: 'Lưu', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Thêm chương đầu tiên' })).toBeVisible()
  await page.getByRole('link', { name: 'Thư viện', exact: true }).click()
  await page.getByRole('button', { name: `Thao tác cho ${name}` }).click()
  await page.getByRole('menuitem', { name: 'Sửa thông tin' }).click()
  await expect(page.locator('.cover img')).toHaveAttribute('src', first!)
  const coverTwo = await page.screenshot()
  await page.locator('input[type=file]').setInputFiles({ name: 'qa-replacement.png', mimeType: 'image/png', buffer: coverTwo })
  await expect(page.locator('.cover img')).not.toHaveAttribute('src', first!)
  await page.getByRole('button', { name: 'Lưu', exact: true }).click()
  await page.getByRole('button', { name: `Thao tác cho ${name}` }).click()
  await page.getByRole('menuitem', { name: 'Sửa thông tin' }).click()
  await expect(page.locator('.cover img')).toBeVisible()
  await page.getByRole('button', { name: 'Xóa ảnh bìa' }).click()
  await page.getByRole('button', { name: 'Lưu', exact: true }).click()
  await page.getByRole('button', { name: `Thao tác cho ${name}` }).click()
  await page.getByRole('menuitem', { name: 'Sửa thông tin' }).click()
  await expect(page.locator('.cover img')).toHaveCount(0)
})
