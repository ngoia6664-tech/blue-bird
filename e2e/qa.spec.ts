import { test, expect, type Page } from '@playwright/test'

async function login(page: Page) {
  await page.goto('/')
  await page.waitForFunction(() => '__signInForTest' in window)
  await page.evaluate(() => (window as any).__signInForTest('ngoia6664@gmail.com'))
  await expect(page.getByRole('heading', { name: 'Hôm nay viết gì nào?' })).toBeVisible()
}
async function work(page: Page, name: string) {
  await page.getByRole('link', { name: 'Tạo tác phẩm', exact: true }).first().click()
  await page.getByLabel('Tên tác phẩm *').fill(`QA ${name} ${Date.now()}`)
  await page.getByRole('button', { name: 'Lưu', exact: true }).click()
  await page.getByRole('button', { name: 'Thêm chương đầu tiên' }).click()
  await expect(page.locator('.prose')).toHaveAttribute('contenteditable', 'true')
}
async function write(page: Page, text: string) {
  await page.locator('.prose').fill(text)
  await expect(page.locator('.save-state')).toHaveText('Đã đồng bộ', { timeout: 15000 })
}

test('QA validates work fields and persists metadata, alias search and status filter', async ({ page }) => {
  await login(page)
  await page.getByRole('link', { name: 'Tạo tác phẩm', exact: true }).first().click()
  await page.getByRole('button', { name: 'Lưu', exact: true }).click()
  await expect(page.getByText('Hãy nhập tên tác phẩm.')).toBeVisible()
  await page.getByLabel('Tên tác phẩm *').fill('x'.repeat(201))
  await page.getByRole('button', { name: 'Lưu', exact: true }).click()
  await expect(page.getByText('Tên tối đa 200 ký tự.')).toBeVisible()
  const name = `QA metadata ${Date.now()}`
  const alias = `Bí danh ${Date.now()}`
  await page.getByLabel('Tên tác phẩm *').fill(name)
  await page.getByLabel('Tên khác').fill(alias)
  await page.getByLabel('Mô tả').fill('Mô tả tiếng Việt có dấu')
  await page.getByLabel('Ghi chú riêng').fill('Dữ liệu thử QA')
  await page.getByRole('combobox', { name: 'Trạng thái', exact: true }).selectOption({ label: 'Tạm dừng' })
  await page.getByRole('button', { name: 'Lưu', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Thêm chương đầu tiên' })).toBeVisible()
  await page.getByRole('link', { name: 'Thư viện', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Tìm tác phẩm' }).fill(alias)
  await expect(page.locator('.work-card')).toHaveCount(1)
  await expect(page.locator('.work-card')).toContainText(name)
  await page.getByLabel('Lọc theo trạng thái').selectOption({ label: 'Đang viết' })
  await expect(page.locator('.work-card')).toHaveCount(0)
  await page.getByLabel('Lọc theo trạng thái').selectOption({ label: 'Tạm dừng' })
  await expect(page.locator('.work-card')).toHaveCount(1)
  await page.getByRole('button', { name: `Thao tác cho ${name}` }).click()
  await page.getByRole('menuitem', { name: 'Sửa thông tin' }).click()
  await expect(page.getByLabel('Mô tả')).toHaveValue('Mô tả tiếng Việt có dấu')
  await expect(page.getByLabel('Ghi chú riêng')).toHaveValue('Dữ liệu thử QA')
})

test('QA manual version restore preserves the replaced content', async ({ page }) => {
  await login(page); await work(page, 'versions')
  await write(page, 'Bản đầu tiên.')
  await page.getByRole('button', { name: 'Lịch sử phiên bản', exact: true }).click()
  page.once('dialog', d => d.accept('QA bản đầu'))
  await page.getByRole('button', { name: 'Lưu phiên bản hiện tại' }).click()
  await expect(page.getByRole('button', { name: /QA bản đầu/ })).toBeVisible()
  await write(page, 'Bản thứ hai.')
  await page.getByRole('button', { name: /QA bản đầu/ }).click()
  await expect(page.locator('.version-preview .prose')).toHaveText('Bản đầu tiên.')
  page.once('dialog', d => d.accept())
  await page.getByRole('button', { name: 'Khôi phục bản này' }).click()
  await expect(page.locator('.chapter-editor .prose')).toHaveText('Bản đầu tiên.')
  await expect(page.locator('.save-state')).toHaveText('Đã đồng bộ')
  await page.getByRole('button', { name: /Trước khi khôi phục/ }).click()
  await expect(page.locator('.version-preview .prose')).toHaveText('Bản thứ hai.')
})

