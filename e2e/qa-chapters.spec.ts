import { test, expect } from '@playwright/test'

test('QA duplicate reorder trash restore chapter and persist metadata', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('dialog', d => d.accept())
  await page.goto('/')
  await page.waitForFunction(() => '__signInForTest' in window)
  await page.evaluate(() => (window as any).__signInForTest('ngoia6664@gmail.com'))
  await page.getByRole('link', { name: 'Tạo tác phẩm', exact: true }).first().click()
  await page.getByLabel('Tên tác phẩm *').fill(`QA chapters ${Date.now()}`)
  await page.getByRole('button', { name: 'Lưu', exact: true }).click()
  await page.getByRole('button', { name: 'Thêm chương đầu tiên' }).click()
  await expect(page.locator('.prose')).toHaveAttribute('contenteditable', 'true')
  await page.locator('.prose').fill('Nội dung để nhân bản.')
  await expect(page.locator('.save-state')).toHaveText('Đã đồng bộ lên cloud', { timeout: 15000 })
  await page.getByLabel('Tiêu đề chương', { exact: true }).fill('Tiêu đề QA')
  await page.getByLabel('Số chương', { exact: true }).click()
  await page.getByRole('button', { name: 'Thao tác cho Chương 1', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Nhân bản', exact: true }).click()
  const copy = page.getByRole('button', { name: 'Chương 1 (bản sao) Tiêu đề QA', exact: true })
  await expect(copy).toBeVisible()
  await copy.click()
  await expect(page.locator('.prose')).toHaveText('Nội dung để nhân bản.')
  await page.getByRole('button', { name: 'Thao tác cho Chương 1 (bản sao)', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Chuyển lên', exact: true }).click()
  await expect(page.locator('.chapter-list').first().locator('.chapter-item').first()).toContainText('bản sao')
  await page.getByRole('button', { name: 'Thao tác cho Chương 1 (bản sao)', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Đưa vào thùng rác', exact: true }).click()
  await expect(copy).toHaveCount(0)
  await page.getByRole('button', { name: 'Thùng rác (1)' }).click()
  await page.getByRole('button', { name: 'Thao tác cho Chương 1 (bản sao) trong thùng rác', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Khôi phục', exact: true }).click()
  await copy.click()
  await expect(page.locator('.prose')).toHaveText('Nội dung để nhân bản.')
  await page.reload()
  await expect(page.getByLabel('Tiêu đề chương', { exact: true })).toHaveValue('Tiêu đề QA')
  await expect(page.locator('.prose')).toHaveText('Nội dung để nhân bản.')
  expect(errors).toEqual([])
})

test('QA immediate reload retains text before autosave debounce', async ({ page }) => {
  await page.goto('/')
  await page.waitForFunction(() => '__signInForTest' in window)
  await page.evaluate(() => (window as any).__signInForTest('ngoia6664@gmail.com'))
  await page.getByRole('link', { name: 'Tạo tác phẩm', exact: true }).first().click()
  await page.getByLabel('Tên tác phẩm *').fill(`QA quick reload ${Date.now()}`)
  await page.getByRole('button', { name: 'Lưu', exact: true }).click()
  await page.getByRole('button', { name: 'Thêm chương đầu tiên' }).click()
  for (let i = 1; i <= 3; i++) {
    await expect(page.locator('.prose')).toHaveAttribute('contenteditable', 'true')
    const content = `Nội dung tiếng Việt trước khi tải lại ${i}.`
    await page.locator('.prose').fill(content)
    await page.reload()
    await expect(page.locator('.prose')).toHaveText(content)
  }
})
